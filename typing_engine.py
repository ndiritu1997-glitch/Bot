"""Keyboard-event-based typing engine.

This module simulates typing by sending individual key events through the OS
(via pynput's keyboard controller, which uses Windows SendInput under the
hood). It does NOT paste from the clipboard, and it does NOT attempt to hide
that the events are generated by software.

Responsibilities:
  * KeyboardBackend  - real vs dry-run key output, with release-all on stop.
  * Pacer            - human-like delays, long breaks, progress, state saves,
                       and stop checks. Shared by all typing loops.
  * type_text(...)   - type a plain string (Word body text, code files).
  * type_rows(...)   - type CSV rows into a spreadsheet, cell by cell.

Resume is handled through the Pacer, which keeps `RunState.position` current
and persists it so a run can continue from the next unit.
"""

from __future__ import annotations

import random
import time
from dataclasses import dataclass
from typing import Callable, List, Optional, Sequence

import config
from state_manager import RunState, save_state


class StopRequested(Exception):
    """Raised when the emergency stop (hotkey or Ctrl+C) fires."""


# ---------------------------------------------------------------------------
# Keyboard backend
# ---------------------------------------------------------------------------


class KeyboardBackend:
    """Sends key events, or pretends to in dry-run mode."""

    def __init__(self, dry_run: bool) -> None:
        self.dry_run = dry_run
        self._controller = None
        self._Key = None
        if not dry_run:
            # Imported lazily so dry-run/tests work without pynput installed.
            from pynput.keyboard import Controller, Key  # type: ignore

            self._controller = Controller()
            self._Key = Key

    # -- primitive outputs --------------------------------------------------

    def type_char(self, ch: str) -> None:
        if self.dry_run:
            return
        self._controller.type(ch)  # type: ignore[union-attr]

    def press_enter(self) -> None:
        self._tap(self._Key.enter if self._Key else None)

    def press_tab(self) -> None:
        self._tap(self._Key.tab if self._Key else None)

    def press_backspace(self) -> None:
        self._tap(self._Key.backspace if self._Key else None)

    def _tap(self, key) -> None:
        if self.dry_run or key is None:
            return
        self._controller.press(key)   # type: ignore[union-attr]
        self._controller.release(key)  # type: ignore[union-attr]

    # -- safety -------------------------------------------------------------

    def release_all(self) -> None:
        """Release modifier keys that might be held if we stop mid-stroke."""
        if self.dry_run or self._controller is None or self._Key is None:
            return
        for key in (
            self._Key.shift,
            self._Key.ctrl,
            self._Key.alt,
            self._Key.cmd,
        ):
            try:
                self._controller.release(key)
            except Exception:
                pass


# ---------------------------------------------------------------------------
# Pacer: delays, breaks, progress, state
# ---------------------------------------------------------------------------


@dataclass
class ProgressInfo:
    percent: int
    position: int
    total: int


class Pacer:
    """Owns timing, breaks, progress reporting and state persistence."""

    def __init__(
        self,
        state: RunState,
        stop_check: Callable[[], bool],
        logger,
        on_progress: Optional[Callable[[ProgressInfo], None]] = None,
        on_break: Optional[Callable[[int], None]] = None,
        on_resume_from_break: Optional[Callable[[], None]] = None,
    ) -> None:
        self.state = state
        self._stop_check = stop_check
        self.logger = logger
        self._on_progress = on_progress
        self._on_break = on_break
        self._on_resume_from_break = on_resume_from_break

        self._active_since_break = 0.0
        self._next_break_at = random.uniform(
            config.BREAK_AFTER_MIN_SECONDS, config.BREAK_AFTER_MAX_SECONDS
        )
        self._last_saved = time.monotonic()
        self._last_progress_percent = -1

    # -- stop ---------------------------------------------------------------

    def check_stop(self) -> None:
        if self._stop_check():
            raise StopRequested()

    def _sleep(self, seconds: float, *, counts_as_active: bool) -> None:
        """Sleep in short slices so a stop is responsive. Optionally count the
        time as active typing time (used for pacing breaks)."""
        remaining = seconds
        slice_len = 0.1
        while remaining > 0:
            self.check_stop()
            chunk = slice_len if remaining > slice_len else remaining
            time.sleep(chunk)
            remaining -= chunk
            if counts_as_active:
                self._active_since_break += chunk
                self.state.active_seconds += chunk

    # -- delays -------------------------------------------------------------

    def delay_after(self, ch: str, next_ch: Optional[str]) -> None:
        """Pause an appropriate, randomized amount after typing `ch`."""
        # Base per-key delay.
        delay = random.uniform(config.MIN_KEY_DELAY, config.MAX_KEY_DELAY)

        if ch in ".!?":
            delay += random.uniform(config.PUNCT_PAUSE_MIN, config.PUNCT_PAUSE_MAX)
        elif ch == " ":
            delay += random.uniform(config.WORD_PAUSE_MIN, config.WORD_PAUSE_MAX)

        self._sleep(delay, counts_as_active=True)

    def pause_line(self, *, paragraph: bool) -> None:
        if paragraph:
            delay = random.uniform(
                config.PARAGRAPH_PAUSE_MIN, config.PARAGRAPH_PAUSE_MAX
            )
        else:
            delay = random.uniform(config.LINE_PAUSE_MIN, config.LINE_PAUSE_MAX)
        self._sleep(delay, counts_as_active=True)

    # -- breaks -------------------------------------------------------------

    def maybe_break(self) -> None:
        """Take a long human-style break if enough active time has elapsed."""
        if self._active_since_break < self._next_break_at:
            return

        length = random.uniform(
            config.BREAK_LENGTH_MIN_SECONDS, config.BREAK_LENGTH_MAX_SECONDS
        )
        minutes = int(round(length / 60))
        self.logger.info(
            "Taking a break: %d min after %.0f min of typing.",
            minutes,
            self._active_since_break / 60,
        )
        self.state.status = "on_break"
        save_state(self.state)  # so a crash during the break still resumes
        if self._on_break:
            self._on_break(minutes)

        # Break time does NOT count as active typing time.
        self._sleep(length, counts_as_active=False)

        self._active_since_break = 0.0
        self._next_break_at = random.uniform(
            config.BREAK_AFTER_MIN_SECONDS, config.BREAK_AFTER_MAX_SECONDS
        )
        self.state.status = "typing"
        save_state(self.state)
        if self._on_resume_from_break:
            self._on_resume_from_break()

    # -- progress + checkpoint ---------------------------------------------

    def checkpoint(self, position: int, *, force: bool = False) -> None:
        """Advance the saved position and persist state periodically."""
        self.state.position = position
        now = time.monotonic()
        if force or (now - self._last_saved) >= config.STATE_SAVE_EVERY_SECONDS:
            save_state(self.state)
            self._last_saved = now

    def report_progress(self, position: int) -> None:
        total = self.state.total_units or 1
        percent = int(position * 100 / total)
        step = config.PROGRESS_STEP_PERCENT
        bucket = (percent // step) * step
        if bucket != self._last_progress_percent and percent >= 0:
            self._last_progress_percent = bucket
            if self._on_progress:
                self._on_progress(ProgressInfo(bucket, position, total))


# ---------------------------------------------------------------------------
# Typo simulation (optional)
# ---------------------------------------------------------------------------

_ADJACENT = "abcdefghijklmnopqrstuvwxyz"


def _maybe_typo(backend: KeyboardBackend, pacer: Pacer, ch: str) -> None:
    """With low probability, type a wrong letter, pause, backspace, and go on.

    Only applied to plain alphabetic characters, and never changes the final
    output (the correct character is typed by the caller afterwards).
    """
    if not config.ENABLE_TYPOS:
        return
    if not ch.isalpha() or ch.lower() not in _ADJACENT:
        return
    if random.random() >= config.TYPO_PROBABILITY:
        return

    wrong = random.choice(_ADJACENT)
    if wrong == ch.lower():
        return
    backend.type_char(wrong)
    pacer._sleep(  # noqa: SLF001 - intentional internal reuse
        random.uniform(config.TYPO_NOTICE_PAUSE_MIN, config.TYPO_NOTICE_PAUSE_MAX),
        counts_as_active=True,
    )
    backend.press_backspace()


# ---------------------------------------------------------------------------
# Text typing (Word body text, HTML/CSS/JS/PHP source)
# ---------------------------------------------------------------------------


def type_text(
    text: str,
    backend: KeyboardBackend,
    pacer: Pacer,
    start_index: int = 0,
) -> None:
    """Type `text` character by character starting at `start_index`.

    Newlines are sent as Enter. Tabs are sent as Tab. A blank line (two
    newlines in a row) triggers a longer paragraph pause.

    NOTE on code: editors with auto-indent may add indentation of their own on
    Enter. See the README for how to handle this (use an editor/file with
    auto-indent off, or accept the editor's reformatting).
    """
    n = len(text)
    i = start_index
    while i < n:
        pacer.check_stop()
        pacer.maybe_break()

        ch = text[i]
        nxt = text[i + 1] if i + 1 < n else None

        if ch == "\n":
            backend.press_enter()
            paragraph = nxt == "\n"
            pacer.pause_line(paragraph=paragraph)
        elif ch == "\t":
            backend.press_tab()
            pacer.delay_after(" ", nxt)
        elif ch == "\r":
            pass  # swallow carriage returns; Enter handled by \n
        else:
            _maybe_typo(backend, pacer, ch)
            backend.type_char(ch)
            pacer.delay_after(ch, nxt)

        i += 1
        pacer.checkpoint(i)
        pacer.report_progress(i)

    pacer.checkpoint(n, force=True)


def type_fragment(
    text: str,
    backend: KeyboardBackend,
    pacer: Pacer,
) -> None:
    """Type a short string with human delays, stop checks and breaks, but
    WITHOUT touching progress/checkpoint. Used by the PowerPoint path, where
    the caller checkpoints at slide granularity instead of per character.
    """
    n = len(text)
    for i in range(n):
        pacer.check_stop()
        ch = text[i]
        nxt = text[i + 1] if i + 1 < n else None
        if ch == "\n":
            backend.press_enter()
            pacer.pause_line(paragraph=False)
        elif ch == "\t":
            backend.press_tab()
            pacer.delay_after(" ", nxt)
        elif ch == "\r":
            continue
        else:
            backend.type_char(ch)
            pacer.delay_after(ch, nxt)


# ---------------------------------------------------------------------------
# CSV / spreadsheet typing
# ---------------------------------------------------------------------------


def _cell_text(raw: str) -> str:
    """Make a cell value safe to type into Excel.

    Values that would be interpreted as a formula get a leading apostrophe so
    Excel stores them as text rather than evaluating them.
    """
    if raw and raw[0] in config.EXCEL_FORMULA_TRIGGERS:
        return "'" + raw
    return raw


def type_rows(
    rows: Sequence[Sequence[str]],
    backend: KeyboardBackend,
    pacer: Pacer,
    start_index: int = 0,
) -> None:
    """Type CSV `rows` into a spreadsheet cell by cell.

    Navigation: within a row, each value is typed and Tab advances to the next
    column (empty cells are just a Tab). At the end of a row, Enter is pressed;
    Excel returns the cursor to the starting column of the next row.

    `start_index` is a flat cell counter so a run can resume mid-sheet.
    """
    # Flatten to (row_idx, col_idx, is_last_in_row, value) for linear resume.
    flat: List[tuple[int, int, bool, str]] = []
    for r, row in enumerate(rows):
        if not row:
            # Preserve a genuinely blank row: emit one empty, last-in-row cell.
            flat.append((r, 0, True, ""))
            continue
        for c, value in enumerate(row):
            flat.append((r, c, c == len(row) - 1, value))

    total = len(flat)
    i = start_index
    while i < total:
        pacer.check_stop()
        pacer.maybe_break()

        _r, _c, is_last, value = flat[i]
        text = _cell_text(value)

        for j, ch in enumerate(text):
            pacer.check_stop()
            nxt = text[j + 1] if j + 1 < len(text) else None
            backend.type_char(ch)
            pacer.delay_after(ch, nxt)

        if is_last:
            backend.press_enter()
            pacer.pause_line(paragraph=False)
        else:
            backend.press_tab()
            pacer.delay_after(" ", None)

        i += 1
        pacer.checkpoint(i)
        pacer.report_progress(i)

    pacer.checkpoint(total, force=True)
